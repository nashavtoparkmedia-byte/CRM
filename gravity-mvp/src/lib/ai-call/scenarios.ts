/**
 * DB helpers for AI-call scenarios and their parent projects.
 *
 * Projects (AiCallProject) group scenarios by business purpose — lead
 * qualification, churn winback, NPS survey. Each scenario belongs to at most
 * one project; existing scenarios without a project on first list are
 * auto-backfilled to "Квалификация лида" (proj_lead_qual, seeded by migration
 * 20260517000000_add_ai_call_projects).
 *
 * On first read in a fresh database, auto-seeds the default scenario so the
 * settings page never shows an empty list.
 */

import { prisma } from '@/lib/prisma'
import type {
    AiCallGreetingVariant,
    AiCallOutcomeSchema,
    AiCallScenarioConfig,
    AiCallScenarioFragments,
    AiCallScenarioQuestion,
} from './types'
import {
    DEFAULT_SCENARIO_NAME,
    DEFAULT_SCENARIO_DESCRIPTION,
    DEFAULT_SCENARIO_SYSTEM_PROMPT,
    DEFAULT_SCENARIO_QUESTIONS,
    DEFAULT_SCENARIO_TARGET_SEC,
    DEFAULT_SCENARIO_OUTCOME_SCHEMA,
    DEFAULT_SCENARIO_GREETING_VARIANTS,
} from './default-scenario'

// Prisma types for AiCallScenario/AiCallProject are generated after
// `prisma generate`. Cast to `any` so this file compiles before the user
// runs migrations locally — same pattern as aiCallAnalysis/config.ts.
const db = prisma as any

// Fixed ID for the default project (matches migration seed)
export const DEFAULT_PROJECT_ID = 'proj_lead_qual'

/**
 * Идемпотентный сид трёх базовых проектов. Дублирует data-часть миграции
 * 20260517000000_add_ai_call_projects: на базах, созданных через
 * `prisma db push` (VPS), миграции не выполнялись, AiCallProject пуст,
 * и автосид сценария падал с P2003 (FK projectId) → 500 на странице.
 */
async function ensureDefaultProjects(): Promise<void> {
    await db.aiCallProject.createMany({
        data: [
            { id: 'proj_lead_qual', name: 'Квалификация лида', slug: 'lead-qualification', description: 'Холодные/тёплые звонки лидам для квалификации перед передачей менеджеру.', isActive: true, sortOrder: 10 },
            { id: 'proj_churn_winback', name: 'Работа с оттоком', slug: 'churn-winback', description: 'Возврат уходящих или давно неактивных водителей.', isActive: true, sortOrder: 20 },
            { id: 'proj_nps_survey', name: 'Опрос качества', slug: 'nps-survey', description: 'Сбор обратной связи и оценок качества обслуживания у активных водителей.', isActive: true, sortOrder: 30 },
        ],
        skipDuplicates: true,
    })
}

export interface AiCallProjectConfig {
    id: string
    name: string
    slug: string
    description?: string
    sortOrder: number
}

export interface AiCallScenarioWithProject extends AiCallScenarioConfig {
    projectId: string | null
    projectName: string | null
}

function rowToConfig(row: any): AiCallScenarioWithProject {
    return {
        id: row.id,
        name: row.name,
        description: row.description ?? undefined,
        systemPrompt: row.systemPrompt,
        questions: (row.questions as AiCallScenarioQuestion[]) ?? [],
        targetDurationSec: row.targetDurationSec ?? undefined,
        // outcomeSchema is opaque JSON in Prisma. PR #57: scenarios that
        // opted-in get canonical-key validation at finalize-time + LLM
        // tool constraints at runtime. NULL = legacy passthrough.
        outcomeSchema: (row.outcomeSchema as AiCallOutcomeSchema | null) ?? undefined,
        // greetingVariants is opaque JSON in Prisma. PR #62: scenarios
        // that opted-in get A/B variant assignment at call start. NULL
        // = legacy LLM-generated greeting.
        greetingVariants: (row.greetingVariants as AiCallGreetingVariant[] | null) ?? undefined,
        // fragments is opaque JSON in Prisma. PR #63: scenarios that
        // opted-in get composable system-prompt assembly. NULL or
        // missing required slots → legacy monolithic prompt path.
        fragments: (row.fragments as AiCallScenarioFragments | null) ?? undefined,
        projectId: row.projectId ?? null,
        projectName: row.project?.name ?? null,
    }
}

export async function listProjects(opts?: { includeInactive?: boolean }): Promise<AiCallProjectConfig[]> {
    let rows = await db.aiCallProject.findMany({
        where: opts?.includeInactive ? undefined : { isActive: true },
        orderBy: [{ sortOrder: 'asc' }, { createdAt: 'asc' }],
    })
    if (rows.length === 0) {
        await ensureDefaultProjects()
        rows = await listProjectRows(opts)
    }
    return rows.map((r: any) => ({
        id: r.id,
        name: r.name,
        slug: r.slug,
        description: r.description ?? undefined,
        sortOrder: r.sortOrder,
    }))
}

function listProjectRows(opts?: { includeInactive?: boolean }) {
    return db.aiCallProject.findMany({
        where: opts?.includeInactive ? undefined : { isActive: true },
        orderBy: [{ sortOrder: 'asc' }, { createdAt: 'asc' }],
    })
}

export async function getProject(id: string): Promise<AiCallProjectConfig | null> {
    const r = await db.aiCallProject.findUnique({ where: { id } })
    if (!r) return null
    return { id: r.id, name: r.name, slug: r.slug, description: r.description ?? undefined, sortOrder: r.sortOrder }
}

export async function listScenarios(opts?: { includeInactive?: boolean; projectId?: string }): Promise<AiCallScenarioWithProject[]> {
    const where: Record<string, unknown> = {}
    if (!opts?.includeInactive) where.isActive = true
    if (opts?.projectId) where.projectId = opts.projectId

    let rows = await db.aiCallScenario.findMany({
        where,
        orderBy: [{ projectId: 'asc' }, { createdAt: 'asc' }],
        include: { project: { select: { name: true } } },
    })

    // Backfill orphan scenarios (pre-project schema) into the default project.
    const orphans = rows.filter((r: any) => r.projectId == null)
    if (orphans.length > 0) {
        await db.aiCallScenario.updateMany({
            where: { id: { in: orphans.map((r: any) => r.id) } },
            data: { projectId: DEFAULT_PROJECT_ID },
        })
        // Re-read after backfill to include project name
        rows = await db.aiCallScenario.findMany({
            where,
            orderBy: [{ projectId: 'asc' }, { createdAt: 'asc' }],
            include: { project: { select: { name: true } } },
        })
    }

    if (rows.length === 0 && !opts?.projectId) {
        // Auto-seed default scenario into the default project. На пустой базе
        // (db push без data-миграций) сначала гарантируем сам проект — иначе
        // create() падает с P2003 по FK projectId.
        await ensureDefaultProjects()
        const seeded = await createScenario({
            name: DEFAULT_SCENARIO_NAME,
            description: DEFAULT_SCENARIO_DESCRIPTION,
            systemPrompt: DEFAULT_SCENARIO_SYSTEM_PROMPT,
            questions: DEFAULT_SCENARIO_QUESTIONS,
            targetDurationSec: DEFAULT_SCENARIO_TARGET_SEC,
            outcomeSchema: DEFAULT_SCENARIO_OUTCOME_SCHEMA,
            greetingVariants: DEFAULT_SCENARIO_GREETING_VARIANTS,
            projectId: DEFAULT_PROJECT_ID,
        })
        return [seeded]
    }
    return rows.map(rowToConfig)
}

export async function getScenario(id: string): Promise<AiCallScenarioWithProject | null> {
    const row = await db.aiCallScenario.findUnique({
        where: { id },
        include: { project: { select: { name: true } } },
    })
    return row ? rowToConfig(row) : null
}

export async function createScenario(input: {
    name: string
    description?: string
    systemPrompt: string
    questions: AiCallScenarioQuestion[]
    targetDurationSec?: number
    outcomeSchema?: AiCallOutcomeSchema
    greetingVariants?: AiCallGreetingVariant[]
    fragments?: AiCallScenarioFragments
    projectId?: string
}): Promise<AiCallScenarioWithProject> {
    const row = await db.aiCallScenario.create({
        data: {
            name: input.name,
            description: input.description,
            systemPrompt: input.systemPrompt,
            questions: input.questions as any,
            targetDurationSec: input.targetDurationSec,
            outcomeSchema: input.outcomeSchema as any,
            greetingVariants: input.greetingVariants as any,
            fragments: input.fragments as any,
            projectId: input.projectId ?? DEFAULT_PROJECT_ID,
            isActive: true,
        },
        include: { project: { select: { name: true } } },
    })
    return rowToConfig(row)
}

export async function updateScenario(
    id: string,
    patch: {
        name?: string
        description?: string
        systemPrompt?: string
        questions?: AiCallScenarioQuestion[]
        targetDurationSec?: number
        outcomeSchema?: AiCallOutcomeSchema | null
        greetingVariants?: AiCallGreetingVariant[] | null
        fragments?: AiCallScenarioFragments | null
        isActive?: boolean
        projectId?: string
    },
): Promise<AiCallScenarioWithProject> {
    const row = await db.aiCallScenario.update({
        where: { id },
        data: {
            ...(patch.name !== undefined && { name: patch.name }),
            ...(patch.description !== undefined && { description: patch.description }),
            ...(patch.systemPrompt !== undefined && { systemPrompt: patch.systemPrompt }),
            ...(patch.questions !== undefined && { questions: patch.questions as any }),
            ...(patch.targetDurationSec !== undefined && { targetDurationSec: patch.targetDurationSec }),
            ...(patch.outcomeSchema !== undefined && { outcomeSchema: patch.outcomeSchema as any }),
            ...(patch.greetingVariants !== undefined && { greetingVariants: patch.greetingVariants as any }),
            ...(patch.fragments !== undefined && { fragments: patch.fragments as any }),
            ...(patch.isActive !== undefined && { isActive: patch.isActive }),
            ...(patch.projectId !== undefined && { projectId: patch.projectId }),
        },
        include: { project: { select: { name: true } } },
    })
    return rowToConfig(row)
}

export async function deleteScenario(id: string): Promise<void> {
    // Soft delete — keep history for any past AI calls that reference it
    await db.aiCallScenario.update({
        where: { id },
        data: { isActive: false },
    })
}
